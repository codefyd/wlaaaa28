create or replace function public.verify_customer_login(
  p_challenge uuid,
  p_code_hash text,
  p_session_hash text,
  p_session_expires_at timestamptz
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $function$
declare
  v_challenge public.customer_login_challenges%rowtype;
begin
  if p_session_expires_at <= pg_catalog.now()
     or p_session_expires_at > pg_catalog.now() + interval '31 days' then
    raise exception 'INVALID_SESSION_EXPIRY';
  end if;

  select * into v_challenge
  from public.customer_login_challenges
  where id = p_challenge
  for update;

  if not found or v_challenge.used_at is not null then
    return jsonb_build_object('error', 'INVALID_CHALLENGE');
  end if;
  if v_challenge.expires_at <= pg_catalog.now() then
    return jsonb_build_object('error', 'OTP_EXPIRED');
  end if;
  if v_challenge.attempts >= 5 then
    return jsonb_build_object('error', 'OTP_LOCKED');
  end if;
  if v_challenge.code_hash <> p_code_hash then
    update public.customer_login_challenges
      set attempts = least(attempts + 1, 5)
      where id = p_challenge;
    return jsonb_build_object(
      'error', case when v_challenge.attempts + 1 >= 5 then 'OTP_LOCKED' else 'OTP_INVALID' end,
      'attempts_remaining', greatest(5 - (v_challenge.attempts + 1), 0)
    );
  end if;

  update public.customer_login_challenges
    set used_at = pg_catalog.now()
    where id = p_challenge;

  insert into public.customer_sessions(token_hash, customer_id, expires_at)
  values (p_session_hash, v_challenge.customer_id, p_session_expires_at);

  update public.customers
    set verified_at = coalesce(verified_at, pg_catalog.now()),
        verify_attempts = 0,
        verify_locked_until = null
    where id = v_challenge.customer_id;

  return jsonb_build_object(
    'customer_id', v_challenge.customer_id,
    'expires_at', p_session_expires_at
  );
end
$function$;

create or replace function public.create_car_order(
  p_customer uuid,
  p_vehicle_plate text,
  p_vehicle_color text,
  p_vehicle_model text,
  p_note text,
  p_items jsonb,
  p_reward uuid default null,
  p_reward_product uuid default null
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $function$
declare
  v_cafe uuid;
  v_enabled boolean;
  v_min_total numeric(10,2);
  v_order uuid;
  v_order_number bigint;
  v_item jsonb;
  v_product public.products%rowtype;
  v_item_id uuid;
  v_qty integer;
  v_option_ids uuid[];
  v_option_count integer;
  v_option_sum numeric(10,2);
  v_unit numeric(10,2);
  v_subtotal numeric(10,2) := 0;
  v_discount numeric(10,2) := 0;
  v_reward public.rewards%rowtype;
begin
  if jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) < 1
     or jsonb_array_length(p_items) > 50 then
    raise exception 'INVALID_ITEMS';
  end if;
  if char_length(btrim(coalesce(p_vehicle_plate, ''))) not between 2 and 30
     or char_length(btrim(coalesce(p_vehicle_color, ''))) not between 2 and 40 then
    raise exception 'INVALID_VEHICLE';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_customer::text, 7));
  select c.cafe_id, f.car_ordering_enabled, f.order_min_total
    into v_cafe, v_enabled, v_min_total
  from public.customers c
  join public.cafes f on f.id = c.cafe_id and f.is_active = true
  where c.id = p_customer
  for share of c, f;
  if not found then raise exception 'CUSTOMER_NOT_FOUND'; end if;
  if not v_enabled then raise exception 'ORDERING_DISABLED'; end if;

  if exists (
    select 1 from public.orders o
    where o.customer_id = p_customer
      and o.status in ('pending','accepted','preparing','ready')
  ) then raise exception 'ACTIVE_ORDER_EXISTS'; end if;

  insert into public.orders(
    cafe_id, customer_id, vehicle_plate, vehicle_color, vehicle_model, note
  ) values (
    v_cafe, p_customer, upper(left(btrim(p_vehicle_plate), 30)),
    left(btrim(p_vehicle_color), 40), nullif(left(btrim(p_vehicle_model), 80), ''),
    nullif(left(btrim(p_note), 500), '')
  ) returning id, order_number into v_order, v_order_number;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_qty := coalesce((v_item->>'quantity')::integer, 0);
    if v_qty < 1 or v_qty > 50 then raise exception 'INVALID_QUANTITY'; end if;

    select * into v_product from public.products
    where id = (v_item->>'product_id')::uuid
      and cafe_id = v_cafe and is_active = true and is_available = true
    for share;
    if not found then raise exception 'PRODUCT_UNAVAILABLE'; end if;

    select coalesce(array_agg(distinct value::uuid), '{}'::uuid[])
      into v_option_ids
    from jsonb_array_elements_text(coalesce(v_item->'option_ids', '[]'::jsonb));

    select count(*)::integer, coalesce(sum(o.price_delta), 0)::numeric(10,2)
      into v_option_count, v_option_sum
    from public.product_options o
    where o.id = any(v_option_ids)
      and o.product_id = v_product.id and o.cafe_id = v_cafe and o.is_active = true;
    if v_option_count <> coalesce(array_length(v_option_ids, 1), 0) then
      raise exception 'INVALID_OPTIONS';
    end if;
    if exists (
      select 1 from public.product_options o
      where o.id = any(v_option_ids)
      group by o.group_name
      having count(*) filter (where o.is_multiple = false) > 0 and count(*) > 1
    ) then raise exception 'INVALID_OPTIONS'; end if;

    v_unit := v_product.base_price + v_option_sum;
    insert into public.order_items(
      order_id, cafe_id, product_id, product_name, base_unit_price,
      unit_price, quantity, line_total
    ) values (
      v_order, v_cafe, v_product.id, v_product.name, v_product.base_price,
      v_unit, v_qty, v_unit * v_qty
    ) returning id into v_item_id;

    insert into public.order_item_options(
      order_item_id, cafe_id, option_id, option_name, price_delta
    )
    select v_item_id, v_cafe, o.id, o.name, o.price_delta
    from public.product_options o
    where o.id = any(v_option_ids)
    order by o.sort_order, o.id;

    v_subtotal := v_subtotal + (v_unit * v_qty);
  end loop;

  if v_subtotal < coalesce(v_min_total, 0) then raise exception 'MIN_TOTAL_NOT_MET'; end if;

  if p_reward is not null then
    select * into v_reward from public.rewards
    where id = p_reward and customer_id = p_customer and cafe_id = v_cafe
    for update;
    if not found or v_reward.status <> 'available'
       or (v_reward.expires_at is not null and v_reward.expires_at <= pg_catalog.now())
       or v_reward.reward_type <> 'free_cup' then
      raise exception 'REWARD_NOT_AVAILABLE';
    end if;
    if p_reward_product is null then raise exception 'REWARD_PRODUCT_REQUIRED'; end if;
    if exists (
      select 1 from public.reward_reservations r
      where r.reward_id = p_reward and r.consumed_at is null and r.released_at is null
    ) then raise exception 'REWARD_RESERVED'; end if;

    -- The free-cup reward covers exactly one product base price. Options remain payable.
    select least(oi.base_unit_price, v_subtotal) into v_discount
    from public.order_items oi
    where oi.order_id = v_order and oi.product_id = p_reward_product
    order by oi.created_at, oi.id limit 1;
    if v_discount is null then raise exception 'REWARD_PRODUCT_NOT_IN_ORDER'; end if;

    update public.order_items set reward_applied = true
    where id = (
      select oi.id from public.order_items oi
      where oi.order_id = v_order and oi.product_id = p_reward_product
      order by oi.created_at, oi.id limit 1
    );

    update public.orders set reward_id = p_reward where id = v_order;
    insert into public.reward_reservations(cafe_id, customer_id, reward_id, order_id)
    values (v_cafe, p_customer, p_reward, v_order);
  end if;

  update public.orders
    set subtotal = v_subtotal, discount_total = v_discount,
        total = greatest(v_subtotal - v_discount, 0)
    where id = v_order;

  insert into public.order_status_history(order_id, cafe_id, status)
  values (v_order, v_cafe, 'pending');

  return jsonb_build_object(
    'order_id', v_order,
    'order_number', v_order_number,
    'subtotal', v_subtotal,
    'discount_total', v_discount,
    'total', greatest(v_subtotal - v_discount, 0)
  );
end
$function$;

create or replace function public.customer_mark_order_arrived(
  p_customer uuid,
  p_order uuid,
  p_parking_spot text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $function$
declare
  v_order public.orders%rowtype;
begin
  select * into v_order from public.orders
  where id = p_order and customer_id = p_customer
  for update;
  if not found then raise exception 'ORDER_NOT_FOUND'; end if;
  if v_order.status not in ('pending','accepted','preparing','ready') then
    raise exception 'ORDER_NOT_ACTIVE';
  end if;
  update public.orders
    set arrived_at = coalesce(arrived_at, pg_catalog.now()),
        parking_spot = nullif(left(btrim(p_parking_spot), 50), '')
    where id = p_order;
  return jsonb_build_object('order_id', p_order, 'arrived_at', coalesce(v_order.arrived_at, pg_catalog.now()));
end
$function$;

