create or replace function public.staff_update_car_order(
  p_order uuid,
  p_status text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_order public.orders%rowtype;
  v_staff uuid;
begin
  if (select auth.uid()) is null then raise exception 'UNAUTHENTICATED'; end if;
  select * into v_order from public.orders where id = p_order for update;
  if not found then raise exception 'ORDER_NOT_FOUND'; end if;
  if not public.is_staff_of(v_order.cafe_id) then raise exception 'NOT_AUTHORIZED'; end if;
  select s.id into v_staff from public.staff s
  where s.user_id = (select auth.uid()) and s.cafe_id = v_order.cafe_id and s.is_active = true
  limit 1;

  if not (
    (v_order.status = 'pending' and p_status in ('accepted','cancelled')) or
    (v_order.status = 'accepted' and p_status in ('preparing','ready','cancelled')) or
    (v_order.status = 'preparing' and p_status in ('ready','cancelled')) or
    (v_order.status = 'ready' and p_status in ('cancelled','no_show'))
  ) then raise exception 'INVALID_STATUS_TRANSITION'; end if;

  update public.orders set
    status = p_status,
    accepted_at = case when p_status = 'accepted' then pg_catalog.now() else accepted_at end,
    preparing_at = case when p_status = 'preparing' then pg_catalog.now() else preparing_at end,
    ready_at = case when p_status = 'ready' then pg_catalog.now() else ready_at end,
    cancelled_at = case when p_status in ('cancelled','no_show') then pg_catalog.now() else cancelled_at end,
    payment_status = case when p_status in ('cancelled','no_show') then 'void' else payment_status end
  where id = p_order;

  if p_status in ('cancelled','no_show') then
    update public.reward_reservations set released_at = pg_catalog.now()
    where order_id = p_order and consumed_at is null and released_at is null;
  end if;
  insert into public.order_status_history(order_id, cafe_id, status, changed_by)
  values (p_order, v_order.cafe_id, p_status, v_staff);
  return jsonb_build_object('order_id', p_order, 'status', p_status);
end
$function$;

create or replace function public.complete_car_order(p_order uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_order public.orders%rowtype;
  v_staff uuid;
  v_visit_result jsonb;
  v_visit uuid;
begin
  if (select auth.uid()) is null then raise exception 'UNAUTHENTICATED'; end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_order::text, 11));
  select * into v_order from public.orders where id = p_order for update;
  if not found then raise exception 'ORDER_NOT_FOUND'; end if;
  if not public.is_staff_of(v_order.cafe_id) then raise exception 'NOT_AUTHORIZED'; end if;
  if v_order.status not in ('accepted','preparing','ready') then
    raise exception 'ORDER_NOT_READY';
  end if;
  select s.id into v_staff from public.staff s
  where s.user_id = (select auth.uid()) and s.cafe_id = v_order.cafe_id and s.is_active = true
  limit 1;

  if v_order.reward_id is not null then
    update public.rewards set status = 'used', used_at = pg_catalog.now(), used_by_staff = v_staff
    where id = v_order.reward_id and customer_id = v_order.customer_id and status = 'available';
    if not found then raise exception 'REWARD_NOT_AVAILABLE'; end if;
    update public.reward_reservations set consumed_at = pg_catalog.now()
    where order_id = p_order and reward_id = v_order.reward_id
      and consumed_at is null and released_at is null;
  end if;

  if v_order.total > 0 then
    v_visit_result := public.add_visit(
      v_order.customer_id, 1, null,
      'طلب سيارة #' || v_order.order_number::text
    );
    v_visit := (v_visit_result->>'visit_id')::uuid;
  end if;

  update public.orders set status = 'completed', payment_status = 'paid',
    completed_at = pg_catalog.now(), visit_id = v_visit
  where id = p_order;
  insert into public.order_status_history(order_id, cafe_id, status, changed_by)
  values (p_order, v_order.cafe_id, 'completed', v_staff);

  return jsonb_build_object(
    'order_id', p_order,
    'status', 'completed',
    'visit_id', v_visit,
    'loyalty', v_visit_result
  );
end
$function$;

-- Manual redemption must not consume a reward already reserved by a car order.
create or replace function public.redeem_reward(p_reward uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_reward public.rewards%rowtype;
  v_staff uuid;
begin
  select * into v_reward from public.rewards where id = p_reward for update;
  if not found then raise exception 'REWARD_NOT_FOUND'; end if;
  if not public.is_staff_of(v_reward.cafe_id) then raise exception 'NOT_AUTHORIZED'; end if;
  if v_reward.status <> 'available' then raise exception 'REWARD_NOT_AVAILABLE'; end if;
  if exists (
    select 1 from public.reward_reservations r
    where r.reward_id = p_reward and r.consumed_at is null and r.released_at is null
  ) then raise exception 'REWARD_RESERVED'; end if;

  if v_reward.expires_at is not null and v_reward.expires_at < pg_catalog.now() then
    update public.rewards set status = 'expired' where id = p_reward;
    return jsonb_build_object('reward_id', p_reward, 'status', 'expired');
  end if;
  select s.id into v_staff from public.staff s
  where s.user_id = (select auth.uid()) and s.cafe_id = v_reward.cafe_id
    and s.is_active = true limit 1;
  update public.rewards set status = 'used', used_at = pg_catalog.now(), used_by_staff = v_staff
  where id = p_reward and status = 'available';
  if not found then raise exception 'REWARD_NOT_AVAILABLE'; end if;
  return jsonb_build_object('reward_id', p_reward, 'status', 'used');
end
$function$;

create or replace function public.order_report_overview(
  p_cafe uuid,
  p_from timestamptz,
  p_to timestamptz
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_result jsonb;
begin
  if (select auth.uid()) is null or not public.is_owner_of(p_cafe) then
    raise exception 'NOT_AUTHORIZED';
  end if;
  if p_from is null or p_to is null or p_from > p_to
     or p_to - p_from > interval '370 days' then
    raise exception 'INVALID_RANGE';
  end if;

  select jsonb_build_object(
    'totals', jsonb_build_object(
      'orders', count(*),
      'completed', count(*) filter (where o.status = 'completed'),
      'cancelled', count(*) filter (where o.status in ('cancelled','no_show')),
      'active', count(*) filter (where o.status in ('pending','accepted','preparing','ready')),
      'revenue', coalesce(sum(o.total) filter (where o.status = 'completed'), 0),
      'avg_prep_minutes', coalesce(round(avg(extract(epoch from (o.ready_at - o.accepted_at))/60)
        filter (where o.ready_at is not null and o.accepted_at is not null), 1), 0),
      'avg_arrival_wait_minutes', coalesce(round(avg(extract(epoch from (o.completed_at - o.arrived_at))/60)
        filter (where o.completed_at is not null and o.arrived_at is not null), 1), 0)
    ),
    'products', (
      select coalesce(jsonb_agg(jsonb_build_object(
        'name', x.product_name, 'quantity', x.quantity, 'revenue', x.revenue
      ) order by x.quantity desc, x.product_name), '[]'::jsonb)
      from (
        select oi.product_name, sum(oi.quantity)::integer quantity,
          sum(oi.line_total - case when oi.reward_applied then po.discount_total else 0 end)::numeric(12,2) revenue
        from public.order_items oi
        join public.orders po on po.id = oi.order_id
        where po.cafe_id = p_cafe and po.status = 'completed'
          and po.created_at between p_from and p_to
        group by oi.product_name
      ) x
    ),
    'by_hour', (
      select coalesce(jsonb_agg(jsonb_build_object('hour', x.hour_value, 'orders', x.orders)
        order by x.hour_value), '[]'::jsonb)
      from (
        select extract(hour from o2.created_at at time zone 'Asia/Riyadh')::integer as hour_value,
          count(*)::integer orders
        from public.orders o2
        where o2.cafe_id = p_cafe and o2.created_at between p_from and p_to
        group by 1
      ) x
    )
  ) into v_result
  from public.orders o
  where o.cafe_id = p_cafe and o.created_at between p_from and p_to;
  return v_result;
end
$function$;

